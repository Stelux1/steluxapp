import './env.ts';
import { resolve } from 'node:path';
import { Store } from './store.ts';
import { seed } from './seed.ts';
import { createApp } from './http.ts';
import { PostgresDatabase, postgresConfig } from './postgres.ts';
import { runtimeConfig } from './runtime-config.ts';
const config = runtimeConfig(process.env);
const { dataDir } = config;
const database = config.databaseUrl ? new PostgresDatabase(postgresConfig()) : undefined;
const store = new Store(resolve(dataDir, 'stelux.sqlite'), database);
seed(store);
const port = config.port;
const server = createApp(store, dataDir, { releaseProfile: config.profile, distDir: config.distDir }).listen(port, '127.0.0.1', () => console.log(`Blitzkrieg API ready at http://127.0.0.1:${port} (${database ? 'PostgreSQL' : 'SQLite'})`));
for (const signal of ['SIGINT', 'SIGTERM'] as const) process.on(signal, () => server.close(() => { store.close(); process.exit(0); }));
