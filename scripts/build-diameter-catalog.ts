// Turns the capture of Weld Pilot → Material data → Weld diameters into shared/diameter-catalog-data.ts.
//   node --import tsx scripts/build-diameter-catalog.ts <capture .txt with DTROW lines> [output .ts]
// Prints the rows it skipped (test entries, rows without a numeric size in mm, repeated diameter texts).
import { readFileSync, writeFileSync } from 'node:fs';
import { parseDiameterCapture } from '../shared/diameter-catalog.ts';

const [input, output = 'shared/diameter-catalog-data.ts'] = process.argv.slice(2);
if (!input) { console.error('Usage: node --import tsx scripts/build-diameter-catalog.ts <capture.txt> [output.ts]'); process.exit(1); }
const { rows, skipped } = parseDiameterCapture(readFileSync(input, 'utf8'));
if (!rows.length) { console.error('The capture holds no DTROW lines; nothing written.'); process.exit(1); }
const lines = rows.map(row => `  { ref: ${row.ref}, diameter: ${JSON.stringify(row.diameter)}, size: ${row.size}, sizeinch: ${row.sizeinch}, outline: ${row.outline}, sorting: ${row.sorting} },`);
writeFileSync(output, `import type { DiameterCatalogRow } from './diameter-catalog.ts';

/**
 * Generated by \`node --import tsx scripts/build-diameter-catalog.ts <capture of Weld diameters>\`; do not edit by hand.
 * ${rows.length} rows of the reference catalog (${skipped.length} skipped).
 */
export const DIAMETER_CATALOG: DiameterCatalogRow[] = [
${lines.join('\n')}
];
`);
console.log(`${rows.length} rows written to ${output}; ${skipped.length} skipped.`);
for (const row of skipped) console.log(`skipped ref ${row.ref ?? '?'} "${row.diameter}": ${row.reason}`);
