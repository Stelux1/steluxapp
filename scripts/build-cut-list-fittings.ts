// Turns the client's cut list workbook (sheet Codes: CODE, DESCRIPTION, DIAMETER, SIZE) into shared/cut-list-fittings-data.ts.
//   node --import tsx scripts/build-cut-list-fittings.ts "<Chameleon_Cut_list_Prototype 7.xlsm>" [output .ts]
// The workbook is read as data with exceljs (its macros never run). Sheet Diameteres (hidden) gives the diameter chart.
// Prints the rows it skipped (no code, a take-off that is not a number, a repeated code).
import { writeFileSync } from 'node:fs';
import ExcelJS from 'exceljs';
import type { FittingCatalogRow } from '../shared/cut-list.ts';

const [input, output = 'shared/cut-list-fittings-data.ts'] = process.argv.slice(2);
if (!input) { console.error('Usage: node --import tsx scripts/build-cut-list-fittings.ts <workbook.xlsm> [output.ts]'); process.exit(1); }
const workbook = new ExcelJS.Workbook();
await workbook.xlsx.readFile(input);
/** A cell as text: rich text joined (the sheet colours the size part of a code), a formula by its result. */
const text = (value: ExcelJS.CellValue): string => {
  if (value === null || value === undefined) return '';
  if (typeof value === 'object' && 'richText' in value) return value.richText.map(part => part.text).join('');
  if (typeof value === 'object' && 'result' in value) return String(value.result ?? '');
  if (value instanceof Date) return value.toISOString();
  return String(value);
};
const codes = workbook.getWorksheet('Codes');
if (!codes) { console.error('The workbook has no sheet Codes; nothing written.'); process.exit(1); }
const rows: FittingCatalogRow[] = [], skipped: string[] = [], seen = new Set<string>();
codes.eachRow((row, number) => {
  if (number === 1) return;
  const [code, description, diameter, size] = [1, 2, 3, 4].map(column => text(row.getCell(column).value).trim());
  if (!code && !description && !diameter && !size) return;
  if (!code) { skipped.push(`row ${number}: no code`); return; }
  const takeoff = Number(size.replace(',', '.'));
  if (!size || !Number.isFinite(takeoff)) { skipped.push(`row ${number} ${code}: SIZE "${size}" is not a number`); return; }
  if (seen.has(code.toLowerCase())) { skipped.push(`row ${number} ${code}: the code appears again`); return; }
  seen.add(code.toLowerCase());
  rows.push([number, code, description.replace(/\s+/g, ' '), diameter, takeoff]);
});
const chart: string[] = [];
workbook.getWorksheet('Diameteres')?.eachRow((row, number) => { const value = text(row.getCell(1).value).trim(); if (number >= 7 && value && value !== '0') chart.push(value); });
if (!rows.length) { console.error('The sheet Codes holds no fittings; nothing written.'); process.exit(1); }
writeFileSync(output, `import type { FittingCatalogRow } from './cut-list.ts';

/**
 * Generated by \`node --import tsx scripts/build-cut-list-fittings.ts <Chameleon_Cut_list_Prototype 7.xlsm>\`; do not edit by hand.
 * ${rows.length} fittings of the sheet Codes (${skipped.length} skipped): [row in the sheet, code, description, diameter, take-off mm].
 */
export const CUT_LIST_FITTINGS: FittingCatalogRow[] = [
${rows.map(row => `  ${JSON.stringify(row)},`).join('\n')}
];

/** The diameter chart of the workbook (hidden sheet Diameteres): the DIA choices of a cut list line. */
export const CUT_LIST_DIAMETERS: string[] = ${JSON.stringify(chart)};
`);
console.log(`${rows.length} fittings and ${chart.length} diameters written to ${output}; ${skipped.length} skipped.`);
for (const line of skipped) console.log(`  skipped ${line}`);
