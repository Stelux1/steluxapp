// Turns the client's MaterialDB.xlsx into shared/data/material-db-base.ts (the default Material database of every new main project).
//   node --import tsx scripts/build-material-base.ts <MaterialDB.xlsx> [output .ts]
// Sheet MaterialDB_WvB holds the materials (rows without a Material No are empty formula rows and are skipped); a Material Type,
// Material group, size, schedule or description without a stored formula result is read from sheet INDEX (column A = Material No).
import { writeFileSync } from 'node:fs';
import ExcelJS from 'exceljs';
import type { MaterialBaseFile } from '../shared/material-base.ts';

const [input, output = 'shared/data/material-db-base.ts'] = process.argv.slice(2);
if (!input) { console.error('Usage: node --import tsx scripts/build-material-base.ts <MaterialDB.xlsx> [output.ts]'); process.exit(1); }
const clean = (value: unknown) => String(value ?? '').replace(/\s+/g, ' ').trim();
const text = (cell: ExcelJS.Cell) => { try { return clean(cell.text); } catch { return ''; } };

const workbook = new ExcelJS.Workbook();
await workbook.xlsx.readFile(input);
const sheet = workbook.getWorksheet('MaterialDB_WvB'), index = workbook.getWorksheet('INDEX');
if (!sheet || !index) { console.error('The workbook needs the sheets MaterialDB_WvB and INDEX.'); process.exit(1); }
// INDEX: A Material No, B group, C part material, E size, G class / schedule, H description, I material type.
const lookup = new Map<string, Record<'group' | 'part' | 'size' | 'schedule' | 'description' | 'type', string>>();
index.eachRow((row, number) => {
  if (number === 1) return;
  const key = text(row.getCell(1));
  if (key) lookup.set(key, { group: text(row.getCell(2)), part: text(row.getCell(3)), size: text(row.getCell(5)), schedule: text(row.getCell(7)), description: text(row.getCell(8)), type: text(row.getCell(9)) });
});

const lists = { groups: new Map<string, number>(), parts: new Map<string, number>(), types: new Map<string, number>(), uoms: new Map<string, number>() };
const at = (map: Map<string, number>, value: string) => { if (!value) return -1; let found = map.get(value); if (found === undefined) { found = map.size; map.set(value, found); } return found; };
const rows: MaterialBaseFile['rows'] = [], seen = new Set<string>(), filled = { type: 0, part: 0, fallback: 0 };
for (let number = 2; number <= sheet.rowCount; number++) {
  const row = sheet.getRow(number), materialNo = text(row.getCell(4));
  if (!materialNo) continue;
  if (seen.has(materialNo)) throw new Error(`Material No ${materialNo} is repeated (row ${number}).`);
  seen.add(materialNo);
  const found = lookup.get(materialNo), digits = /(\d{6})$/.exec(text(row.getCell(2)))?.[1];
  if (!digits) throw new Error(`Row ${number} has no ArticleNo of six digits.`);
  const pick = (cached: string, fallback: string | undefined) => { if (cached) return cached; if (fallback) filled.fallback++; return fallback ?? ''; };
  const type = pick(text(row.getCell(10)), found?.type), part = pick(text(row.getCell(11)), found?.part);
  if (type) filled.type++;
  if (part) filled.part++;
  const group = pick(text(row.getCell(1)), found?.group), uom = text(row.getCell(8)) || 'EA';
  rows.push([at(lists.groups, group), digits, text(row.getCell(3)), materialNo, pick(text(row.getCell(5)), found?.size), pick(text(row.getCell(6)), found?.schedule), pick(text(row.getCell(7)), found?.description), at(lists.uoms, uom), at(lists.types, type), at(lists.parts, part)]);
}
const names = (map: Map<string, number>) => [...map.keys()];
const file: MaterialBaseFile = { source: 'MaterialDB.xlsx (sheet MaterialDB_WvB, types and parts from sheet INDEX)', groups: names(lists.groups), parts: names(lists.parts), types: names(lists.types), uoms: names(lists.uoms), rows };
const body = `{\n  "source": ${JSON.stringify(file.source)},\n  "groups": ${JSON.stringify(file.groups)},\n  "parts": ${JSON.stringify(file.parts)},\n  "types": ${JSON.stringify(file.types)},\n  "uoms": ${JSON.stringify(file.uoms)},\n  "rows": [\n${rows.map(row => '    ' + JSON.stringify(row)).join(',\n')}\n  ]\n}`;
writeFileSync(output, `import type { MaterialBaseFile } from '../material-base.ts';\n\n/**\n * Generated by \`node --import tsx scripts/build-material-base.ts <MaterialDB.xlsx>\`; do not edit by hand.\n * ${rows.length} materials, ${file.parts.length} material parts, ${file.types.length} types of material (see shared/material-base.ts for the row layout).\n */\nexport const MATERIAL_DB_BASE: MaterialBaseFile = ${body};\n`);
console.log(`${rows.length} materials, ${file.groups.length} groups, ${file.parts.length} parts, ${file.types.length} types, uoms ${file.uoms.join('/')}; with type ${filled.type}, with part ${filled.part}; ${filled.fallback} values read from INDEX.`);
