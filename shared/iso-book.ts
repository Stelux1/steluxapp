/**
 * ISO Book: one merged PDF assembled from checked parts (spec: reference/montavar/mto.md "ISO Book").
 * Shared by the server (assembly) and the dialog (labels, order, limits).
 */

/** Limits enforced by the server; the dialog quotes them. */
export const ISO_BOOK_LIMITS = {
  /** Isometrics in one request. */
  isometrics: 100,
  /** Pages of the finished book (generated parts, uploaded PDFs, images, cover). */
  pages: 2000,
  /** Stored size of every uploaded file that goes into the book, in bytes. */
  inputBytes: 100 * 1024 * 1024,
};

export const BOOK_GROUPINGS = ['by-isometric', 'by-part'] as const;
export type BookGrouping = typeof BOOK_GROUPINGS[number];
export const BOOK_GROUPING_LABELS: Record<BookGrouping, string> = {
  'by-isometric': 'One book per isometric, one after the other',
  'by-part': 'One book, grouped by part type',
};

/** Where a part comes from. `registry` parts are generated by the document registry (server/pdf/documents.ts). */
export type BookPartSource = 'cover' | 'files' | 'generated' | 'both' | 'custom';
export interface BookPartInfo {
  key: string; label: string;
  /** Short note of the source shown under the label. */
  source: BookPartSource;
  /** False when the part cannot be included; `reason` then says why (nothing is faked). */
  available: boolean; reason?: string;
  /** Custom attachment names only: before or after the isometric drawing. */
  position?: 'Before Isometric' | 'After Isometric';
}

