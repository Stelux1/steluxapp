export interface BookRequest { isoIds: string[]; parts: string[]; grouping: BookGrouping }
export interface BookPartsResponse {
  isometrics: { id: string; isoNo: string }[];
  parts: BookPartInfo[];
  limits: typeof ISO_BOOK_LIMITS;
}

/** The request body of `POST /api/iso-book`; the message names what is wrong. Pure so client and server share it. */
export function bookRequestError(body: unknown): string {
  if (!body || typeof body !== 'object') return 'Choose the isometrics and the parts of the book.';
  const { isoIds, parts, grouping } = body as Record<string, unknown>;
  if (!Array.isArray(isoIds) || !isoIds.length || isoIds.some(id => typeof id !== 'string' || !id || id.length > 100)) return 'Choose at least one isometric.';
  if (new Set(isoIds).size > ISO_BOOK_LIMITS.isometrics) return `A book request may contain at most ${ISO_BOOK_LIMITS.isometrics} isometrics. Split it into several requests.`;
  if (!Array.isArray(parts) || !parts.length || parts.length > 200 || parts.some(part => typeof part !== 'string' || !part || part.length > 120)) return 'Choose at least one part of the book.';
  if (grouping !== undefined && !(BOOK_GROUPINGS as readonly unknown[]).includes(grouping)) return 'Choose how several isometrics are combined.';
  return '';
}
